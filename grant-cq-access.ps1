<#
Gives the load user every ComplianceQuest permission set and permission set group, and a
permission set (Atlas_Seed_Record_Types) that makes every active CQ record type visible,
so the seed loads without "invalid record type" errors.

Scratch orgs only: it grants everything, including CQ Migration User, which skips CQ's
validation rules. It stops on an org that does not look like a scratch org unless you add
-NotScratchOk.

Run from the atlas-seed folder, after creating the org and before loading the seed:
  powershell -ExecutionPolicy Bypass -File .\grant-cq-access.ps1 -Org atlas-seed
Safe to run again: anything already assigned is skipped.
#>
param(
    [Parameter(Mandatory = $true)][string]$Org,
    [switch]$NotScratchOk
)
$ErrorActionPreference = 'Stop'
Set-Location -Path $PSScriptRoot

# Runs an sf command with --json and returns its result, or stops with sf's own message.
function Invoke-Sf([string[]]$SfArgs) {
    $ErrorActionPreference = 'Continue'   # sf may print notices on stderr; only the JSON status counts
    $raw = (& sf @SfArgs --json 2>$null) | Out-String
    try { $res = $raw | ConvertFrom-Json } catch { throw "sf $($SfArgs -join ' ') returned no JSON:`n$raw" }
    if ($res.status -ne 0) { throw "sf $($SfArgs -join ' ') failed: $($res.message)" }
    return $res.result
}

# 1. Scratch org check (scratch orgs carry an expiration date).
# (PowerShell names ignore case, so this must not be called $org: that is the -Org parameter.)
$orgInfo = (Invoke-Sf @('data', 'query', '--query', 'SELECT Name, TrialExpirationDate FROM Organization', '--target-org', $Org)).records[0]
if (-not $orgInfo.TrialExpirationDate -and -not $NotScratchOk) {
    Write-Host "$($orgInfo.Name) does not look like a scratch org. This script grants every CQ permission, including"
    Write-Host "CQ Migration User. Add -NotScratchOk only if you are sure."
    exit 1
}

# 2. Build Atlas_Seed_Record_Types from the record types this org actually has.
$rts = (Invoke-Sf @('data', 'query', '--query',
    "SELECT SobjectType, DeveloperName, NamespacePrefix FROM RecordType WHERE NamespacePrefix IN ('compliancequest','cqext','cqcollab') AND IsActive = true ORDER BY SobjectType, DeveloperName",
    '--target-org', $Org)).records
$xml = @(
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<PermissionSet xmlns="http://soap.sforce.com/2006/04/metadata">',
    '    <description>Every active ComplianceQuest record type, so the Atlas seed can load. Generated by grant-cq-access.ps1.</description>',
    '    <hasActivationRequired>false</hasActivationRequired>',
    '    <label>Atlas Seed Record Types</label>'
)
foreach ($r in $rts) {
    $xml += '    <recordTypeVisibilities>'
    $xml += "        <recordType>$($r.SobjectType).$($r.NamespacePrefix)__$($r.DeveloperName)</recordType>"
    $xml += '        <visible>true</visible>'
    $xml += '    </recordTypeVisibilities>'
}
$xml += '</PermissionSet>'
$dir = Join-Path $PSScriptRoot 'force-app\main\default\permissionsets'
New-Item -ItemType Directory -Force -Path $dir | Out-Null
[IO.File]::WriteAllLines((Join-Path $dir 'Atlas_Seed_Record_Types.permissionset-meta.xml'), [string[]]$xml, (New-Object Text.UTF8Encoding $false))
Write-Host "Record types: $($rts.Count). Deploying Atlas_Seed_Record_Types..."
Invoke-Sf @('project', 'deploy', 'start', '--source-dir', 'force-app', '--target-org', $Org, '--wait', '20') | Out-Null

# 3. Assign every CQ permission set and group, plus Atlas_Seed_Record_Types, to the load user.
Write-Host 'Assigning CQ permission sets and groups...'
$run = Invoke-Sf @('apex', 'run', '--file', 'scripts\assign-cq-access.apex', '--target-org', $Org)
if (-not $run.success) { throw "Assignment script failed: $($run.compileProblem) $($run.exceptionMessage)" }
$run.logs -split "`n" | Where-Object { $_ -match 'USER_DEBUG' } | ForEach-Object { Write-Host (($_ -split '\|')[-1]).Trim() }
Write-Host 'Done. Load the seed next.'
